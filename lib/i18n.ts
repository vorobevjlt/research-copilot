export type AppLocale = "ru" | "en";

export function isAppLocale(value: unknown): value is AppLocale {
  return value === "ru" || value === "en";
}

export function localeCode(locale: AppLocale) {
  return locale === "ru" ? "ru-RU" : "en-US";
}

